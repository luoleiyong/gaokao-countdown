// 等级：按 (i + c) % 10 分布 —— 上上 20% / 上 30% / 中 30% / 静心 20%
function levelOf(i, c) {
  const r = (i + c) % 10;
  if (r <= 1) return '上上签';
  if (r <= 3) return '上签';
  if (r <= 6) return '中签';
  return '静心签';
}

const topics = Object.keys(wishes);
const signs = [];
for (let i = 0; i < poems.length; i++) {
  for (let c = 0; c < topics.length; c++) {
    const topic = topics[c];
    const wish = wishes[topic][(i * 7 + c) % 10];
    signs.push({
      no: i * 7 + c + 1,
      level: levelOf(i, c),
      poem: poems[i],
      wish,
      tag: topic
    });
  }
}

